/**
 * Builds `docs/tools.md`: every tool with its read/write mode (see tool-policy.ts), the
 * Dockhand endpoint it calls and a one-sentence summary. Pure and timestamp-free so the
 * generator (scripts/generate-tool-list.mjs) is a no-op when nothing changed.
 */

import type { ToolEndpointEntry } from '../openapi/tool-endpoint-map.js';

export interface ToolListDocDeps {
  endpointMap: Readonly<Record<string, ToolEndpointEntry>>;
  metaToolNames: readonly string[];
  classify: (name: string) => 'read' | 'write';
  summaryOf: (name: string) => string | undefined;
  openApiCommit: string;
}

/** First sentence, single line, table-safe. */
function firstSentence(text: string | undefined): string {
  const flat = (text ?? '').replace(/\s+/g, ' ').trim();
  if (!flat) return '—';
  const cut = flat.split(/(?<=[.!?])\s/)[0];
  return cut.replace(/\|/g, '\\|');
}

export function buildToolListDoc(deps: ToolListDocDeps): string {
  const names = [...new Set([...Object.keys(deps.endpointMap), ...deps.metaToolNames])].sort();

  let reads = 0;
  const rows = names.map((name) => {
    const mode = deps.classify(name);
    if (mode === 'read') reads += 1;
    const entry = Object.prototype.hasOwnProperty.call(deps.endpointMap, name) ? deps.endpointMap[name] : undefined;
    const method = entry ? entry.method.toUpperCase() : '—';
    const path = entry ? `\`${entry.path}\`` : '—';
    return `| \`${name}\` | ${mode} | ${method} | ${path} | ${firstSentence(deps.summaryOf(name))} |`;
  });

  return [
    '<!-- Auto-generated by scripts/generate-tool-list.mjs — do not edit by hand. Regenerate with `npm run build && npm run docs:tools`. -->',
    '',
    '# Tools',
    '',
    `Every tool with its read/write mode. Under \`MCP_READ_ONLY=true\` only \`read\` tools are registered; see [README → Read-only mode and tool filter](../README.md#read-only-mode-and-tool-filter). Endpoints and summaries come from the Dockhand OpenAPI spec pinned at commit \`${deps.openApiCommit}\`.`,
    '',
    `**Tools:** ${names.length} · **read:** ${reads} · **write:** ${names.length - reads}`,
    '',
    '| Tool | Mode | Method | Path | Summary |',
    '| --- | --- | --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
}
